"""Measured action-open -> UE-feedback frame chains with an explicit exact-GT service queue (composition v2).

Boundaries: B's corrected close-out instants (``closeout_01``) joined to the service's own per-request records
(``numeric_gt/service/FRAMES.jsonl`` in the sealed attempt roots). All instants are ms after action-open on one
CLOCK_MONOTONIC_RAW host clock.

Prediction path (sequential)       A action-open -> 7-channel input start (state build, actor, plan, GT hook)
                                   B 7-channel input   C codec -> first send   D send span   E uplink
                                   F reassembly -> prediction materialised   H -> prediction received at service
GT path (prep worker, sequential)  freeze hand-off (UE freeze -> service), then FREEZE (GT preparation), BIND,
                                   CONFIRM_SEND, PUBLISH (publication); each request keeps its own service dispatch
                                   wait, send, worker execution and reply. GT is ready at the service at the
                                   PUBLISH reply. Dispatch waits are never folded into preparation durations.
Score channel (one worker, serial) the service dispatches one request at a time; a dispatch decision is taken at
                                   max(earliest ready, channel free); PREDICTION (priority 0) beats TARGET
                                   (priority 1) when both are pending; each request has its own dispatch latency,
                                   send, execution and reply; the second request joins and scores. Other frames'
                                   score work (post-scoring RESULT/ARCHIVE jobs, or a slow previous decision)
                                   blocks the channel: measured as carry-in, regenerated by the environment.
Return                             R scoring end (second request's worker end) -> UE receipt.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from enum import Enum
from typing import Mapping, Optional

COMPOSITION_MODEL = "SERVICE_QUEUE_V2"


class ChainError(ValueError):
    """A measured chain violates the boundary or queue contract."""


class UncalibratedTermError(RuntimeError):
    """A latency term needed for this decision has no calibrated support. Training must not proceed."""

    def __init__(self, term: str, reason: str) -> None:
        super().__init__(f"UNCALIBRATED {term}: {reason}")
        self.term = term
        self.reason = reason


class Ordering(str, Enum):
    GT_FIRST = "GT_FIRST"                  # TARGET dispatched first (admit only); PREDICTION scores
    PREDICTION_FIRST = "PREDICTION_FIRST"  # PREDICTION dispatched first (store only); TARGET scores


INSTANTS = (
    "actor_end", "ue_input_start", "ue_input_end", "ue_encode_start", "ue_encode_end", "ue_first_send",
    "ue_last_send", "edge_first_datagram", "edge_reassembly_complete", "edge_compute_start", "edge_compute_end",
    "prediction_materialized", "service_prediction_received", "gt_published", "prediction_worker_begin",
    "prediction_worker_end", "target_worker_begin", "target_worker_end", "scoring_worker_end", "result_sent",
    "feedback_emitted", "ue_receipt",
)
PREDICTION_PATH = ("A", "B", "C", "D", "E", "F", "H")
_PREDICTION_INSTANTS = (("A", "ue_input_start"), ("B", "ue_input_end"), ("C", "ue_first_send"),
                        ("D", "ue_last_send"), ("E", "edge_reassembly_complete"), ("F", "prediction_materialized"),
                        ("H", "service_prediction_received"))
GT_REQUESTS = ("FREEZE", "BIND", "CONFIRM_SEND", "PUBLISH")
SCORE_REQUESTS = ("PREDICTION", "TARGET")
TOLERANCE_MS = 1e-6


@dataclass(frozen=True)
class ChainContextV1:
    mode_id: int
    q_e4: int
    family: str
    quantizer: str
    wire_bytes: int
    prior_ul_mcs: int
    backlog_bytes: float
    camera_si: float
    radar_p40: float
    network_profile: str
    cold: bool


@dataclass(frozen=True)
class RequestSpanV1:
    """One service->worker request: dispatch latency after the decision, send, worker execution, reply."""

    dispatch: float
    send: float
    execute: float
    reply: float


@dataclass(frozen=True)
class ServiceRecordV1:
    """The service's own per-request instants for one decision (ms after action-open)."""

    freeze_received: float
    requests: Mapping[str, Mapping[str, float]]   # op -> {svc_begin, wk_begin, wk_end, svc_end}
    prediction_received: float
    carry_in: Optional[float]                    # score channel busy-until from other frames, if any
    post_scoring_end: Optional[float]            # last post-scoring score-channel reply of this frame


@dataclass(frozen=True)
class FrameChainV1:
    source_id: str
    frame_id: int
    context: ChainContextV1
    instants: Mapping[str, Optional[float]]
    scoring_request_op: str
    q_perc: Optional[float]
    controller_resolution: Optional[str]
    service: Optional[ServiceRecordV1] = None
    quality: Mapping[str, object] = field(default_factory=dict)   # per-class fields when delivered

    @property
    def chain_id(self) -> str:
        return f"{self.source_id}#{self.frame_id}"


@dataclass(frozen=True)
class RoleCostsV1:
    """Request spans by role. A chain measures the two roles of its realized order; donors fill the others."""

    target_admit: Optional[RequestSpanV1] = None
    prediction_score: Optional[RequestSpanV1] = None
    prediction_store: Optional[RequestSpanV1] = None
    target_score: Optional[RequestSpanV1] = None
    donor_chain_id: Optional[str] = None


@dataclass(frozen=True)
class StageVectorV1:
    """Joint per-frame stage vector (ms); drawn whole from one chain, never from pooled marginals."""

    chain_id: str
    A: float
    B: float
    C: float
    D: float
    E: float
    F: float
    H: float
    gt_segments: tuple[tuple[str, float], ...]     # freeze hand-off, then per GT request wait/send/exec/reply
    dispatch_prediction: float
    dispatch_target: float
    costs: RoleCostsV1
    R: float
    post_span: float                                # second request's reply -> last post-scoring reply
    carry_in: Optional[float]                       # measured channel busy-until (ms after this action-open)
    realized_ordering: Ordering
    bind_end: float                                 # BIND reply at the service (CONFIRM_SEND send dependency)
    reply_missing: bool = False
    subsplits: Mapping[str, float] = field(default_factory=dict)

    @property
    def G(self) -> float:
        """GT ready at the service (PUBLISH reply)."""
        return sum(v for _, v in self.gt_segments)

    def with_uplink(self, uplink_ms: float) -> "StageVectorV1":
        if not math.isfinite(uplink_ms) or uplink_ms < 0:
            raise UncalibratedTermError("E_uplink", f"adjusted uplink {uplink_ms!r} is not a valid duration")
        return replace(self, E=float(uplink_ms))

    def with_costs(self, costs: RoleCostsV1) -> "StageVectorV1":
        return replace(self, costs=costs)


@dataclass(frozen=True)
class CompositionV1:
    ordering: Ordering
    prediction_at_service: float
    gt_ready: float
    scoring_end: float
    receipt: Optional[float]
    channel_busy_until: float
    critical_path: tuple[tuple[str, float], ...]
    instants: Mapping[str, float]


def _num(row: Mapping, key: str) -> Optional[float]:
    value = row.get(key)
    if value is None:
        return None
    value = float(value)
    if not math.isfinite(value):
        raise ChainError(f"{key} is not finite")
    return value


def chain_from_boundary_row(row: Mapping, *, source_id: str, context: ChainContextV1,
                            service: Optional[ServiceRecordV1] = None,
                            quality: Optional[Mapping[str, object]] = None) -> FrameChainV1:
    instants = {name: _num(row, name) for name in INSTANTS}
    missing = [name for name, value in instants.items() if value is None and name != "ue_receipt"]
    if missing:
        raise ChainError(f"frame {row.get('frame_id')}: missing instants {missing}")
    op = row.get("scoring_request_op")
    if op not in ("PREDICTION", "TARGET"):
        raise ChainError(f"frame {row.get('frame_id')}: scoring_request_op {op!r}")
    q = row.get("q_perc")
    return FrameChainV1(source_id=source_id, frame_id=int(row["frame_id"]), context=context, instants=instants,
                        scoring_request_op=op, q_perc=None if q is None else float(q),
                        controller_resolution=row.get("controller_resolution"), service=service,
                        quality=dict(quality or {}))


def service_records(frames: list[Mapping]) -> dict[int, ServiceRecordV1]:
    """Per-decision service records, with cross-frame score-channel occupancy (carry-in) from every frame."""
    score_work = [(q["begin"], q["end"], int(r["frame_id"])) for r in frames for q in r.get("requests", [])
                  if q.get("worker") == "score"]
    out = {}
    for r in frames:
        if not r.get("decision"):
            continue
        ao = r["action_open_raw_ns"]
        ms = lambda ns: (ns - ao) / 1e6
        events = {(e["role"], e["name"]): e["raw_ns"] for e in r["events"]}
        requests = {}
        for q in r.get("requests", []):
            if q["op"] in GT_REQUESTS + SCORE_REQUESTS and q["op"] not in requests and q.get("status") == "OK":
                t = q["timing"]
                requests[q["op"]] = {"svc_begin": ms(q["begin"]), "wk_begin": ms(t["begin_raw_ns"]),
                                     "wk_end": ms(t["end_raw_ns"]), "svc_end": ms(q["end"])}
        if (set(requests) != set(GT_REQUESTS + SCORE_REQUESTS) or ("service", "freeze_received") not in events
                or ("service", "prediction_received") not in events):
            continue          # not a complete scored decision; the boundary row will be rejected as incomplete
        first_dispatch = min(q["begin"] for q in r["requests"] if q["op"] in SCORE_REQUESTS)
        blocking = [end for begin, end, fid in score_work if fid != int(r["frame_id"]) and begin < first_dispatch]
        second_end = max(requests[op]["svc_end"] for op in SCORE_REQUESTS)
        post = [ms(q["end"]) for q in r["requests"] if q.get("worker") == "score" and q["op"] not in SCORE_REQUESTS]
        out[int(r["frame_id"])] = ServiceRecordV1(
            freeze_received=ms(events[("service", "freeze_received")]), requests=requests,
            # B's boundary: first statement of the service PREDICTION handler (the record's separate
            # prediction_received_raw_ns field is stamped ~4 us later and is not used).
            prediction_received=ms(events[("service", "prediction_received")]),
            carry_in=ms(max(blocking)) if blocking else None,
            post_scoring_end=max(post) if post else second_end)
    return out


def _span(req: Mapping[str, float], decision_at: float) -> RequestSpanV1:
    return RequestSpanV1(dispatch=req["svc_begin"] - decision_at, send=req["wk_begin"] - req["svc_begin"],
                         execute=req["wk_end"] - req["wk_begin"], reply=req["svc_end"] - req["wk_end"])


def decompose(chain: FrameChainV1) -> StageVectorV1:
    """Invert one measured chain into its joint stage vector; reject chains that violate the queue rule."""
    if chain.service is None:
        raise ChainError(f"{chain.chain_id}: composition {COMPOSITION_MODEL} needs the service request record")
    t, s = chain.instants, chain.service
    seq = [0.0] + [t[name] for _, name in _PREDICTION_INSTANTS]
    if any(b < a - TOLERANCE_MS for a, b in zip(seq, seq[1:])):
        raise ChainError(f"{chain.chain_id}: prediction-path instants are not monotone")
    stage = {label: seq[i + 1] - seq[i] for i, (label, _) in enumerate(_PREDICTION_INSTANTS)}
    req = s.requests
    checks = (("service_prediction_received", s.prediction_received), ("gt_published", req["PUBLISH"]["wk_end"]),
              ("prediction_worker_begin", req["PREDICTION"]["wk_begin"]),
              ("prediction_worker_end", req["PREDICTION"]["wk_end"]),
              ("target_worker_begin", req["TARGET"]["wk_begin"]), ("target_worker_end", req["TARGET"]["wk_end"]))
    for name, value in checks:
        if abs(t[name] - value) > 1e-3:
            raise ChainError(f"{chain.chain_id}: boundary {name} disagrees with the service record")

    # GT path: freeze hand-off, then each prep request's own wait + send + exec + reply (never merged).
    segments, previous = [("gt_freeze_handoff", s.freeze_received)], s.freeze_received
    for op in GT_REQUESTS:
        span = _span(req[op], previous)
        if min(span.dispatch, span.send, span.execute, span.reply) < -TOLERANCE_MS:
            raise ChainError(f"{chain.chain_id}: negative {op} interval")
        label = op.lower()
        segments += [(f"gt_{label}_dispatch", span.dispatch), (f"gt_{label}_send", span.send),
                     (f"gt_{label}_execute", span.execute), (f"gt_{label}_reply", span.reply)]
        previous = req[op]["svc_end"]

    # Score channel: verify the priority/serial rule, then measure each request relative to its decision instant.
    r_p, r_t = s.prediction_received, req["PUBLISH"]["svc_end"]
    p, q = req["PREDICTION"], req["TARGET"]
    gt_first = q["svc_begin"] < p["svc_begin"]
    first, second = (q, p) if gt_first else (p, q)
    r_first, r_second = (r_t, r_p) if gt_first else (r_p, r_t)
    free = -math.inf if s.carry_in is None else s.carry_in
    decision_1 = max(min(r_p, r_t), free)
    pending_p = r_p <= decision_1
    if gt_first and pending_p:
        raise ChainError(f"{chain.chain_id}: TARGET dispatched first although PREDICTION was pending (priority)")
    if not gt_first and not pending_p:
        raise ChainError(f"{chain.chain_id}: PREDICTION dispatched first before it was ready")
    if second["svc_begin"] < first["svc_end"] - TOLERANCE_MS:
        raise ChainError(f"{chain.chain_id}: score requests overlap; the channel is not serial")
    span_1 = _span(first, decision_1)
    span_2 = _span(second, max(r_second, first["svc_end"]))
    for span in (span_1, span_2):
        if min(span.dispatch, span.send, span.execute, span.reply) < -TOLERANCE_MS:
            raise ChainError(f"{chain.chain_id}: negative score-channel interval")
    expected_op = "PREDICTION" if gt_first else "TARGET"
    if chain.scoring_request_op != expected_op or abs(second["wk_end"] - t["scoring_worker_end"]) > 1e-3:
        raise ChainError(f"{chain.chain_id}: the scoring request is not the second dispatched request")
    if gt_first:
        costs = RoleCostsV1(target_admit=span_1, prediction_score=span_2)
        d_p, d_t = span_2.dispatch, span_1.dispatch
    else:
        costs = RoleCostsV1(prediction_store=span_1, target_score=span_2)
        d_p, d_t = span_1.dispatch, span_2.dispatch
    receipt = t["ue_receipt"]
    r = 0.0 if receipt is None else receipt - second["wk_end"]
    if r < -TOLERANCE_MS:
        raise ChainError(f"{chain.chain_id}: receipt precedes scoring end")
    subsplits = {"A_state_and_actor": t["actor_end"], "C_encode": t["ue_encode_end"] - t["ue_encode_start"],
                 "E_access": t["edge_first_datagram"] - t["ue_last_send"],
                 "F_compute": t["edge_compute_end"] - t["edge_compute_start"]}
    if receipt is not None:
        subsplits["R_downlink"] = receipt - t["feedback_emitted"]
    return StageVectorV1(
        chain_id=chain.chain_id, gt_segments=tuple(segments), dispatch_prediction=d_p, dispatch_target=d_t,
        costs=replace(costs), R=r, post_span=max(0.0, s.post_scoring_end - second["svc_end"]),
        carry_in=s.carry_in, realized_ordering=Ordering.GT_FIRST if gt_first else Ordering.PREDICTION_FIRST,
        bind_end=req["BIND"]["svc_end"], reply_missing=receipt is None, subsplits=subsplits, **stage)


_MEASURED = object()


def compose(vector: StageVectorV1, *, carry_in=_MEASURED) -> CompositionV1:
    """Explicit queue: prediction and GT race to one serial, priority-ordered score channel.

    ``carry_in`` defaults to the chain's measured channel occupancy (exact reproduction); the environment passes
    its own carry-over from the previous decision instead.
    """
    cum, instants = 0.0, {}
    for label, name in _PREDICTION_INSTANTS:
        cum += getattr(vector, label)
        instants[name] = cum
    r_p = cum
    last_send = vector.A + vector.B + vector.C + vector.D
    if last_send > vector.bind_end + TOLERANCE_MS:
        raise UncalibratedTermError("gt_confirm_send_dependency",
                                    "UE send would finish after BIND; CONFIRM_SEND waiting on the send is unmeasured")
    r_t = vector.G
    free_in = vector.carry_in if carry_in is _MEASURED else carry_in
    free = -math.inf if free_in is None else free_in
    decision_1 = max(min(r_p, r_t), free)
    gt_first = not (r_p <= decision_1)               # PREDICTION (priority 0) wins whenever it is pending
    costs = vector.costs
    first_span, second_span = ((costs.target_admit, costs.prediction_score) if gt_first
                               else (costs.prediction_store, costs.target_score))
    roles = ("target_admit", "prediction_score") if gt_first else ("prediction_store", "target_score")
    ordering = Ordering.GT_FIRST if gt_first else Ordering.PREDICTION_FIRST
    if first_span is None or second_span is None:
        raise UncalibratedTermError("worker_request_costs", f"{ordering.value} needs {roles}, which chain "
                                    f"{vector.chain_id} did not measure and no same-stratum donor supplied")
    d_first = vector.dispatch_target if gt_first else vector.dispatch_prediction
    d_second = vector.dispatch_prediction if gt_first else vector.dispatch_target
    r_second = r_p if gt_first else r_t
    begin_1 = decision_1 + d_first
    end_1 = begin_1 + first_span.send + first_span.execute + first_span.reply
    decision_2 = max(r_second, end_1)
    begin_2 = decision_2 + d_second
    scoring_end = begin_2 + second_span.send + second_span.execute
    end_2 = scoring_end + second_span.reply
    receipt = None if vector.reply_missing else scoring_end + vector.R

    # Critical path, each segment once, ending at the receipt.
    pred_path = [(s, getattr(vector, s)) for s in PREDICTION_PATH]
    gt_path = list(vector.gt_segments)
    if r_second >= end_1:
        path = list(pred_path if gt_first else gt_path)
    else:
        if decision_1 > min(r_p, r_t):
            path = [("score_channel_carry_in", decision_1)]
        else:
            path = list(gt_path if gt_first else pred_path)
        path += [(f"{roles[0]}_dispatch", d_first), (f"{roles[0]}_send", first_span.send),
                 (f"{roles[0]}_execute", first_span.execute), (f"{roles[0]}_reply", first_span.reply)]
    path += [(f"{roles[1]}_dispatch", d_second), (f"{roles[1]}_send", second_span.send),
             (f"{roles[1]}_execute", second_span.execute)]
    if receipt is not None:
        path.append(("R", vector.R))
    first_op, second_op = ("target", "prediction") if gt_first else ("prediction", "target")
    instants.update({"gt_published": r_t - dict(vector.gt_segments)["gt_publish_reply"],
                     f"{first_op}_worker_begin": begin_1 + first_span.send,
                     f"{first_op}_worker_end": begin_1 + first_span.send + first_span.execute,
                     f"{second_op}_worker_begin": begin_2 + second_span.send,
                     f"{second_op}_worker_end": scoring_end, "scoring_worker_end": scoring_end})
    if receipt is not None:
        instants["ue_receipt"] = receipt
    return CompositionV1(ordering=ordering, prediction_at_service=r_p, gt_ready=r_t, scoring_end=scoring_end,
                         receipt=receipt, channel_busy_until=end_2 + vector.post_span,
                         critical_path=tuple(path), instants=instants)
