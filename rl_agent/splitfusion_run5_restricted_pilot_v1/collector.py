"""Pilot Run-5 collector: the corrected Run-5 collector with the pilot latency model, a measured channel trace,
causal fallback frames and the two reward arms. Emits original ``Run5CollectedTransitionV1`` records.

Unchanged from ``CorrectedRun5CollectorV1`` / the original Run-5: the 22-D state (positions 0-20 = Run-4 vector,
21 = SNR through the causal lease adapter), training scaling, previous-outcome features (previous Q_perc stays
Q_perc in both arms), live-parity outcome classes, session break + fresh genesis after a timely-undefined
EVALUATOR_FAULT, holds (2 tensors, one reward request), the inclusive 170-ms deadline and cadence rule.

Pilot changes (each listed in the assumptions record):
* latency: ``latency.PilotLatencyModelV1`` (measured chains, joint SI/P40/MCS selection, interpolation of C/D/E/F
  only, unchanged queue recomposition);
* channel state: decisions read (prior UL MCS, SNR, RLC backlog) together from ONE measured favourable decision
  of the bound sources, in recorded order (the split's trace), one entry per decision, seed-derived start offset;
  the three values are never drawn independently, shuffled or regenerated by a model;
* fallback frames: after each executed decision, a geometric number of fallback frames with per-opportunity
  probability p(executed action) (measured per point, linear in q between measured points), drawn from ONE
  uniform per decision; each frame adds one 100-ms transmit period before the next decision, executes the
  retained a71, is never scored and creates no transition. Two start-up fallbacks are counted at run genesis only;
* reward: CONTROL = the unchanged Run-4 reward (Q_perc - 0.25 L/170, timeout -1); CANDIDATE = Y * (0.7 + 0.3 Q_seg)
  on a timely defined reply, 0 on TIMEOUT. Timely undefined stays an excluded EVALUATOR_FAULT (no transition,
  session reset); late undefined stays TIMEOUT. Undefined quality is never converted to measured zero quality.
* evaluation only: ``receipt_shift_ms`` adds a constant to every composed receipt before classification.
"""
