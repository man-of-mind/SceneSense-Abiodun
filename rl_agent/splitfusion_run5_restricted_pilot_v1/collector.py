GAMMA = 0.99
STARTUP_FALLBACKS = 2
MAX_FALLBACK_FRAMES = 10


class PilotCollectorError(RuntimeError):
    pass


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise PilotCollectorError(message)


def _sha(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


class FallbackModelV1:
    def __init__(self, evidence: Mapping[str, Any]) -> None:
        self.p = {tuple(int(x) for x in key.split(":")): float(v["p"]) for key, v in evidence["per_stratum"].items()}
        _require(evidence["startup_fallbacks_per_run"] == [STARTUP_FALLBACKS], "start-up fallback count differs")
        for mode, points in S.MEASURED_POINTS.items():
            for q in points:
                _require((mode, q) in self.p, f"no fallback evidence for m{mode}/q{q}")

    def probability(self, mode_id: int, q_e4: int) -> float:
        points = S.MEASURED_POINTS[mode_id]
        if q_e4 in points:
            return self.p[(mode_id, q_e4)]
        lo = max(p for p in points if p < q_e4)
        hi = min(p for p in points if p > q_e4)
        w = (q_e4 - lo) / (hi - lo)
        return (1.0 - w) * self.p[(mode_id, lo)] + w * self.p[(mode_id, hi)]

    @staticmethod
    def frames(p: float, u: float) -> int:
        """Geometric count with P(n >= k) = p**k, from one uniform u in [0, 1)."""
        if p <= 0.0 or u >= p:
            return 0
        u = max(u, 1e-300)
        return min(MAX_FALLBACK_FRAMES, int(math.floor(math.log(u) / math.log(p))))


class _Adapter:
    def __init__(self, latency) -> None:
        self.latency = latency
        self.binding_sha256 = _sha({"binding": latency.binding_sha256, "split": latency.split_sha256,
                                    "part": latency.split, "support": S.SUPPORT_SHA256})


class _PilotKernel:
    def __init__(self, collector: "PilotRun5CollectorV1") -> None:
        self._c = collector

    def execute_cycle(self, request) -> environment.KernelCycleResultV1:
        c = self._c
        context = c.context
        identity = request.state.state.state.identity
        opened = request.state.state.boundary.action_open_timestamp_ns
        action = request.action
        q_reward, total_reward, wire_reward, anchor, low, high = c.catalog.draw(
            context.reward_scene_key, mode_id=action.mode_id, q_e4=action.q_e4)
        _, total_held, wire_held, _, held_low, held_high = c.catalog.draw(
            context.held_scene_key, mode_id=action.mode_id, q_e4=action.q_e4)
        draw = c.latency.draw(mode_id=action.mode_id, q_e4=action.q_e4, profile=context.profile,
                              camera_si=context.camera_si, radar_p40=context.radar_p40,
                              prior_ul_mcs=context.prior_ul_mcs, rng=c.chain_rng)
        busy = c.score_channel_busy_until_ns
        carry_in = None if busy is None else (busy - opened) / 1e6
        composed = compose(draw.vector, carry_in=carry_in)
        c.score_channel_busy_until_ns = opened + int(round(composed.channel_busy_until * 1_000_000))
        receipt = None if composed.receipt is None else composed.receipt + c.receipt_shift_ms
        outcome = classify(receipt_elapsed_ns(receipt), q_reward)
        resolution_ns = opened + outcome.resolution_elapsed_ns
        event = contract.RewardEventV1(
            identity=identity, action=action, kind=outcome.kind, action_open_timestamp_ns=opened,
            resolution_timestamp_ns=resolution_ns, clock_domain=CR.CLOCK_DOMAIN, source=c.SCHEMA,
            q_perc=outcome.q_perc if outcome.kind is contract.RewardEventKind.DELIVERED_SUCCESS else None)
        base = identity.decision_seq * 10
        tensors = tuple(
            contract.HoldTensorV1(
                tensor_seq=base + i, offered_payload_bytes=int(total),
                payload_evidence_class=contract.PayloadEvidenceClass.MEASURED_EXACT_ACTION_NODE,
                payload_provenance_sha256=_sha({"scene": key, "row_low": lo, "row_high": hi}),
                reward_requested=i == 0)
            for i, (total, key, lo, hi) in enumerate(((total_reward, context.reward_scene_key, low, high),
                                                      (total_held, context.held_scene_key, held_low, held_high))))
        hold = contract.ActionHoldV1(identity=identity, action=action, tensors=tensors)
        cycle_end = max(resolution_ns + 1, opened + V1.DURATION_NS)
        context.cycle_end_ns = cycle_end
        context.resolution_ns = resolution_ns
        context.executed = (action.mode_id, action.q_e4)
        candidate = (c.catalog.candidate(context.reward_scene_key, mode_id=action.mode_id, q_e4=action.q_e4)
                     if q_reward is not None else None)
        context.resolved = {
            "q_perc_grid": q_reward, "q_defined": q_reward is not None, "candidate_value": candidate,
            "is_grid_point": anchor, "wire_reward": wire_reward, "ingress_bytes": int(wire_reward) + int(wire_held),
            "chain_id": draw.chain_id, "partner_chain_id": draw.partner_chain_id, "donor_chain_id": draw.donor_chain_id,
            "interp_weight": draw.weight, "endpoints": list(draw.endpoints), "mcs_gap": draw.mcs_gap,
            "mcs_outside_stratum_range": draw.mcs_outside_stratum_range, "scene_distance": draw.scene_distance,
            "ordering": composed.ordering.value, "prediction_at_service_ms": composed.prediction_at_service,
            "gt_ready_ms": composed.gt_ready, "scoring_end_ms": composed.scoring_end, "carry_in_ms": carry_in,
            "receipt_ms": receipt, "receipt_shift_ms": c.receipt_shift_ms, "event_kind": outcome.kind.value,
            "resolution_elapsed_ns": outcome.resolution_elapsed_ns}
        return environment.KernelCycleResultV1(hold=hold, reward_event=event, cycle_end_timestamp_ns=cycle_end,
                                               episode_boundary=contract.EpisodeBoundary.CONTINUES)


class PilotRun5CollectorV1(CR.CorrectedRun5CollectorV1):
    SCHEMA = "splitfusion.run5_restricted_pilot.collector.v1"

    def __init__(self, *, latency, catalog, trace, fallback: FallbackModelV1, arm: str, seed: int,
                 authorization: Path, binding_dir: Path, shared_sources: Mapping[str, Any],
                 receipt_shift_ms: float = 0.0) -> None:
        AUTH.verify(authorization, arm=arm, seed=seed, binding_dir=binding_dir)
        _require(arm in AUTH.ARMS, "unknown reward arm")
        _require(latency.split == ("TRAIN" if catalog.split == "fit" else "EVAL"), "chain split and scene split differ")
        _require(trace and all(t["split"] == latency.split for t in trace), "trace split differs")
        self.latency = latency
        self.arm = arm
        self.receipt_shift_ms = float(receipt_shift_ms)
        self.fallback = fallback
        self._trace = tuple((int(t["prior_ul_mcs"]), float(t["snr_db"]), int(t["backlog_bytes"]), t["source_id"],
                             int(t["frame_id"])) for t in trace)
        self.decision_count = 0
        self.diagnostics: list[dict[str, Any]] = []
        self.fallback_frames_total = STARTUP_FALLBACKS
        sources = dict(shared_sources)
        sources["catalog"] = catalog
        super().__init__(calibration=_Adapter(latency), seed=seed, mode="FIXTURE", shared_sources=sources)
        self.collector_binding_sha256 = _sha({"schema": self.SCHEMA, "corrected": self.binding_sha256, "arm": arm,
                                              "catalog": catalog.binding_sha256, "trace": _sha(self._trace),
                                              "fallback": _sha({f"{m}:{q}": v for (m, q), v in fallback.p.items()}), "shift": self.receipt_shift_ms,
                                              "evidence_label": AUTH.EVIDENCE_LABEL})

    # ---------------------------------------------------------------- environment / channel
    def _session_uuid(self) -> str:
        """Valid canonical UUID for every session index.

        The inherited formatter ``...-4c00-8{index:03d}-...`` becomes invalid at index 1000 (five hex digits).
        Indices 0-999 keep that exact string (so every recorded transition digest is unchanged); from 1000 on the
        index moves to the first group with a fixed ``8fff`` fourth group, which the inherited decimal form can never
        produce, so identities stay unique.
        """
        if self._session_index < 1000:
            return super()._session_uuid()
        return f"{self._session_index:08x}-0000-4c00-8fff-{self._seed % 10**12:012d}"

    def _build_env(self) -> environment.Run4SequentialEnvironmentV1:
        return environment.Run4SequentialEnvironmentV1(
            state_provider=self._provider, kernel=_PilotKernel(self), gamma=GAMMA,
            evidence_class=environment.EnvironmentEvidenceClass.SYNTHETIC_MECHANICS_FIXTURE)

    def _channel_reset(self) -> None:
        self._pos = (self._seed * 7919) % len(self._trace)
        self._fallback_rng = random.Random(self._seed * 1_000_003 + 97)

    def _channel_advance(self, context) -> None:            # never called: advance_once is overridden
        raise PilotCollectorError("the pilot channel advances only through advance_once")

    def _channel_profile(self) -> Optional[str]:
        return S.PROFILE

    def _new_context(self):
        mcs, snr, backlog, source_id, frame_id = self._trace[self._pos % len(self._trace)]
        self._mcs_current, self._snr_current, self._backlog_bytes = mcs, snr, backlog
        context = super()._new_context()
        context.trace_entry = (source_id, frame_id)
        return context

    def advance_once(self) -> None:
        context = self.context
        _require(context is not None and context.resolved is not None, "cannot advance an unresolved cycle")
        if context.advanced:
            return
        mode_id, q_e4 = context.executed                   # the action already executed (causal order)
        p = self.fallback.probability(mode_id, q_e4)
        frames = FallbackModelV1.frames(p, self._fallback_rng.random())
        context.fallback_frames_after = frames
        context.fallback_probability = p
        if frames:
            context.cycle_end_ns += frames * contract.TRANSMIT_PERIOD_NS
            self.fallback_frames_total += frames
        self._pos += 1
        context.advanced = True
        self.previous_context = context
        self.context = self._new_context()

    # ---------------------------------------------------------------- one decision
    def collect_transition(self, request: orch.ModeledActionRequestV1):
        _require(type(request) is orch.ModeledActionRequestV1, "foreign request")
        _require(request.decision_ordinal == self.decision_count, "out-of-order decision ordinal")
        _require(S.in_support(request.mode_id, request.q_e4), "action outside the pilot support")
        state = self.current_state_features()
        current = self._env.current_state.state.state
        context = self.context
        action = self._action_identity(request.mode_id, request.q_e4)
        _require((action.mode_id, action.q_e4) == (request.mode_id, request.q_e4), "catalog changed the action")
        cycle = self._env.step(action)
        resolved = dict(context.resolved)
        excluded = isinstance(cycle, environment.ExcludedCycleV1)
        terminal = cycle.terminal
        success = terminal is contract.RewardTerminal.SUCCESS
        if not excluded:
            _require(terminal in (contract.RewardTerminal.SUCCESS, contract.RewardTerminal.TIMEOUT),
                     f"unexpected terminal {terminal}")
        control = None if excluded else float(cycle.reward)
        candidate = None if excluded else (float(resolved["candidate_value"]) if success else 0.0)
        if success:
            _require(resolved["candidate_value"] is not None and resolved["q_perc_grid"] is not None,
                     "SUCCESS without defined quality")
        transition = None
        if excluded:
            self._session_index += 1
            self._open_session()
        else:
            next_state = self.current_state_features()
            transition = RC.Run5CollectedTransitionV1(
                request=request, run4_transition_sha256=cycle.transition_sha256,
                session_uuid=current.identity.session_uuid, decision_seq=current.identity.decision_seq,
                state=state, next_state=next_state, mode_id=action.mode_id, q_e4=action.q_e4,
                reward=control if self.arm == "CONTROL" else candidate, duration=int(cycle.duration),
                discount=GAMMA ** int(cycle.duration), has_next_state=True, terminated=False, truncated=False,
                terminal=terminal.value, q_perc=resolved["q_perc_grid"] if success else None,
                latency_ms=resolved["resolution_elapsed_ns"] / 1e6 if success else None)
        self.diagnostics.append(dict(
            ordinal=self.decision_count, source=request.source, mode_id=action.mode_id, q_e4=action.q_e4,
            terminal=terminal.value, excluded=excluded, control_reward=control, candidate_reward=candidate,
            q_perc=resolved["q_perc_grid"], candidate_value=resolved["candidate_value"], receipt_ms=resolved["receipt_ms"],
            reward_scene_key=context.reward_scene_key, prior_ul_mcs=context.prior_ul_mcs, snr_db=context.snr_db,
            backlog_bytes=context.backlog_bytes, camera_si=context.camera_si, radar_p40=context.radar_p40,
            trace_entry=list(context.trace_entry), mcs_gap=resolved["mcs_gap"],
            mcs_outside_stratum_range=resolved["mcs_outside_stratum_range"], interp_weight=resolved["interp_weight"],
            chain_id=resolved["chain_id"], partner_chain_id=resolved["partner_chain_id"], ordering=resolved["ordering"],
            prediction_at_service_ms=resolved["prediction_at_service_ms"], gt_ready_ms=resolved["gt_ready_ms"],
            fallback_frames_after=getattr(context, "fallback_frames_after", None), state=state))
        self.decision_count += 1
        return transition
